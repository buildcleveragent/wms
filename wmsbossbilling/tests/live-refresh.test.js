import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createLiveRefresh } from '../utils/live-refresh'

describe('live activity refresh lifecycle', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => { vi.clearAllTimers(); vi.useRealTimers() })

  it('refreshes at 30 seconds, pauses in background, resumes immediately', async () => {
    const load = vi.fn().mockResolvedValue(undefined)
    const live = createLiveRefresh(load)
    await live.resume()
    expect(load).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(30000)
    expect(load).toHaveBeenCalledTimes(2)
    live.pause()
    await vi.advanceTimersByTimeAsync(180000)
    expect(load).toHaveBeenCalledTimes(2)
    await live.resume()
    expect(load).toHaveBeenCalledTimes(3)
    live.dispose()
    await vi.advanceTimersByTimeAsync(30000)
    expect(load).toHaveBeenCalledTimes(3)
  })

  it('backs off to 60 then 120 seconds and recovers to 30', async () => {
    const load = vi.fn().mockRejectedValueOnce(new Error('offline')).mockRejectedValueOnce(new Error('offline')).mockResolvedValue(undefined)
    const live = createLiveRefresh(load)
    await live.resume()
    await vi.advanceTimersByTimeAsync(59999)
    expect(load).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(load).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(120000)
    expect(load).toHaveBeenCalledTimes(3)
    await vi.advanceTimersByTimeAsync(30000)
    expect(load).toHaveBeenCalledTimes(4)
    live.dispose()
  })

  it('never overlaps a slow request when filters or visibility change', async () => {
    let finish
    const load = vi.fn().mockImplementationOnce(() => new Promise(resolve => { finish = resolve })).mockResolvedValue(undefined)
    const live = createLiveRefresh(load)
    const first = live.resume()
    live.pause()
    live.resume()
    live.refresh()
    await vi.advanceTimersByTimeAsync(60000)
    expect(load).toHaveBeenCalledTimes(1)
    finish()
    await first
    await vi.advanceTimersByTimeAsync(1)
    expect(load).toHaveBeenCalledTimes(2)
    live.dispose()
  })
})

describe('configurable minute intervals', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => { vi.clearAllTimers(); vi.useRealTimers() })
  it('loads once when off, allows manual reads, and stops retries', async () => {
    const load = vi.fn().mockRejectedValue(new Error('offline'))
    const live = createLiveRefresh(load, { automatic: false, interval: 300000 })
    await live.resume()
    await vi.advanceTimersByTimeAsync(3600000)
    expect(load).toHaveBeenCalledTimes(1)
    await live.refresh()
    expect(load).toHaveBeenCalledTimes(2)
    live.pause()
    await live.resume({ refresh: false })
    await vi.advanceTimersByTimeAsync(3600000)
    expect(load).toHaveBeenCalledTimes(2)
    live.dispose()
  })
  it('honors a ten minute interval, backs off to 20/40 minutes, and reconfigures', async () => {
    const load = vi.fn().mockRejectedValueOnce('offline').mockRejectedValueOnce('offline').mockResolvedValue(null)
    const live = createLiveRefresh(load, { interval: 600000 })
    await live.resume()
    await vi.advanceTimersByTimeAsync(1199999)
    expect(load).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(load).toHaveBeenCalledTimes(2)
    await vi.advanceTimersByTimeAsync(2400000)
    expect(load).toHaveBeenCalledTimes(3)
    live.configure({ automatic: true, interval: 180000 })
    await vi.advanceTimersByTimeAsync(180000)
    expect(load).toHaveBeenCalledTimes(4)
    live.configure({ automatic: false, interval: 180000 })
    await vi.advanceTimersByTimeAsync(3600000)
    expect(load).toHaveBeenCalledTimes(4)
    live.dispose()
  })
})
